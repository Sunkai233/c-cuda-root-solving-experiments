#!/usr/bin/env python3
"""Generate immutable C/CUDA tables from NREL-5MW AeroDyn inputs."""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

import numpy as np

AIRFOILS = ["Cylinder1.dat", "Cylinder2.dat", "DU40_A17.dat", "DU35_A17.dat",
            "DU30_A17.dat", "DU25_A17.dat", "DU21_A17.dat", "NACA64_A17.dat"]


def digest(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def polar(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    pos = next(i for i, s in enumerate(lines) if re.search(r"\bNumAlf\b", s))
    n = int(lines[pos].split()[0])
    rows = []
    for s in lines[pos+1:]:
        try:
            x = [float(v) for v in s.split()[:4]]
        except (ValueError, IndexError):
            continue
        rows.append(x)
        if len(rows) == n:
            break
    a = np.asarray(rows)
    if a.shape != (n, 4) or not np.all(np.diff(a[:, 0]) > 0):
        raise RuntimeError(f"invalid polar {path}")
    return a[:, :3]


def blade(path):
    rows = []
    for s in path.read_text(encoding="utf-8").splitlines():
        f = s.split()
        try:
            if len(f) < 7: continue
            row = [float(x) for x in f[:6]] + [int(f[6])]
        except ValueError:
            continue
        rows.append(row)
        if len(rows) == 19: break
    if len(rows) != 19:
        raise RuntimeError("blade table must have 19 rows")
    return np.asarray(rows)


def doubles(name, values):
    text = [f"BEM_TABLE_QUAL double {name}[{len(values)}] = {{"]
    for i in range(0, len(values), 4):
        text.append("  " + ", ".join(f"{x:.17g}" for x in values[i:i+4]) + ",")
    text.append("};")
    return "\n".join(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--baseline", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    tables = [polar(a.baseline/"Airfoils"/x) for x in AIRFOILS]
    offsets, flat = [], []
    for t in tables:
        offsets.append(len(flat)); flat.extend(t.tolist())
    flat = np.asarray(flat)

    b_all = blade(a.baseline/"NRELOffshrBsline5MW_AeroDyn_blade.dat")
    xyz = b_all[:, :3]
    zlocal = np.empty(19)
    zlocal[0] = 1.5 + np.linalg.norm(xyz[0])
    zlocal[1:] = zlocal[0] + np.cumsum(np.linalg.norm(np.diff(xyz, axis=0), axis=1))
    tip_const_all = 3.0*(zlocal[-1]-zlocal)/(2.0*zlocal)
    hub_const_all = 3.0*(zlocal-1.5)/(2.0*1.5)
    b = b_all[1:18]  # ordinary nodes 2..18
    span, curve, sweep = b[:, 0], b[:, 1], b[:, 2]
    precone = np.deg2rad(-2.5)
    r = np.sqrt(sweep*sweep + (-curve*np.sin(precone)+(1.5+span)*np.cos(precone))**2)

    hashes = "\n".join(f" * {x}: {digest(a.baseline/'Airfoils'/x)}" for x in AIRFOILS)
    out = f"""/* Generated by scripts/generate_bem_real_tables.py; do not hand edit.
 * AeroDyn AFTabMod=1 and InterpOrd=DEFAULT (linear).
{hashes}
 */
#ifndef BEM_REAL_TABLES_H
#define BEM_REAL_TABLES_H
#ifndef BEM_TABLE_QUAL
#define BEM_TABLE_QUAL static const
#endif
#define BEM_AF_COUNT 8
#define BEM_NODE_COUNT 17
#define BEM_POLAR_POINTS {len(flat)}
 BEM_TABLE_QUAL unsigned bem_af_offset[BEM_AF_COUNT] = {{{', '.join(map(str, offsets))}}};
 BEM_TABLE_QUAL unsigned bem_af_count[BEM_AF_COUNT] = {{{', '.join(str(len(x)) for x in tables)}}};
{doubles('bem_alpha_deg', flat[:,0])}
{doubles('bem_cl', flat[:,1])}
{doubles('bem_cd', flat[:,2])}
{doubles('bem_node_r', r)}
{doubles('bem_node_chord', b[:,5])}
{doubles('bem_node_tip_const', tip_const_all[1:18])}
{doubles('bem_node_hub_const', hub_const_all[1:18])}
BEM_TABLE_QUAL unsigned char bem_node_afid[BEM_NODE_COUNT] = {{{', '.join(str(int(x)-1) for x in b[:,6])}}};
#endif
"""
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {a.out}: {len(flat)} polar rows, {len(out)} bytes")


if __name__ == "__main__":
    main()
