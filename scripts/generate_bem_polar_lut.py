#!/usr/bin/env python3
import bisect,re
from pathlib import Path
root=Path(__file__).resolve().parents[1];text=(root/'include'/'bem_real_tables.h').read_text()
def values(name):
 m=re.search(rf'{name}[^=]*=\s*\{{([^}}]*)\}}',text,re.S);return [float(x.strip()) for x in m.group(1).split(',') if x.strip()]
off=[int(x) for x in values('bem_af_offset')];count=[int(x) for x in values('bem_af_count')];alpha=values('bem_alpha_deg');lut=[]
for af in range(8):
 a=alpha[off[af]:off[af]+count[af]]
 for k in range(721):
  x=-180+.5*k;j=max(0,min(len(a)-2,bisect.bisect_right(a,x)-1));lut.append(off[af]+j)
lines=['#ifndef BEM_POLAR_LUT_H','#define BEM_POLAR_LUT_H','/* Generated by scripts/generate_bem_polar_lut.py; 0.5 degree bins. */',f'BEM_TABLE_QUAL unsigned short bem_polar_lut[{len(lut)}] = {{']
for i in range(0,len(lut),24):lines.append('  '+','.join(map(str,lut[i:i+24]))+',')
lines+=['};','#endif',''];(root/'include'/'bem_polar_lut.h').write_text('\n'.join(lines),encoding='utf-8',newline='\n');print(len(lut))
